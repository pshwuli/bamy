// 手机尺寸走一遍：主页看到注册/登录 → 登录 → 总览有钱 → 新建合约扫描实例 → 详情页有"策略状态"
// 用法：node probe_mobile.mjs <base_url> <user> <pass>
import { chromium } from 'playwright'
const [base, user, pass] = process.argv.slice(2)
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 390, height: 844 } })
const errs = []
p.on('pageerror', (e) => errs.push(String(e)))
const ok = (name, cond) => { console.log(cond ? 'PASS' : 'FAIL', name); if (!cond) process.exitCode = 1 }

await p.goto(base + '/', { waitUntil: 'networkidle' })
const reg = p.locator('a[href="/register"]').first()
const login = p.locator('a[href="/login"]').first()
ok('主页顶部有注册按钮且可见', await reg.isVisible())
ok('主页顶部有登录按钮且可见', await login.isVisible())
await login.click()
await p.waitForURL(/login/)
await p.fill('input[autocomplete="username"], input[type="text"]', user)
await p.fill('input[type="password"]', pass)
await p.keyboard.press('Enter')
await p.waitForURL(/dashboard/, { timeout: 15000 })
await p.waitForTimeout(2000)

await p.goto(base + '/instances/new?strategy=market_scanner', { waitUntil: 'networkidle' })
await p.waitForTimeout(1500)
const form = (await p.locator('body').innerText()).replace(/\s+/g, ' ')
ok('新建页显示扫描范围', form.includes('全部 USDT'))
await p.getByText('U 本位合约', { exact: true }).first().click()
await p.waitForTimeout(300)
ok('选合约后出现杠杆', (await p.locator('body').innerText()).includes('逐仓'))
await p.screenshot({ path: './shots/m-create.png', fullPage: true })
await p.getByRole('button', { name: /创建/ }).last().click()
await p.waitForURL(/instances\/\d+$/, { timeout: 15000 })
const url = p.url()
await p.waitForTimeout(1000)
const startBtn = p.locator('.m-actions').getByRole('button', { name: '启动' })
ok('手机详情页有启动按钮', await startBtn.isVisible())
await startBtn.click()
await p.waitForTimeout(25000)
await p.reload({ waitUntil: 'networkidle' })
await p.waitForTimeout(2000)
const detail = (await p.locator('body').innerText()).replace(/\s+/g, ' ')
ok('详情页显示策略状态', detail.includes('策略状态') && detail.includes('粗筛'))
ok('详情页交易对显示为全市场', detail.includes('全市场 · 合约'))
await p.screenshot({ path: './shots/m-detail.png', fullPage: true })
console.log('INSTANCE', url)
await p.goto(base + '/dashboard', { waitUntil: 'networkidle' })
await p.waitForTimeout(2000)
const dash = (await p.locator('body').innerText()).replace(/\s+/g, ' ')
ok('总览显示资金数字', /\d[\d,]*\.\d{2}/.test(dash))
await p.screenshot({ path: './shots/m-dashboard.png' })
console.log('ERR', errs.slice(0, 5))
await b.close()
